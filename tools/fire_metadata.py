#!/usr/bin/env python3
"""Generate resource-free fire parameters from the supported read-only inputs.

The original explosion PSO supplies the VFX hash, explosionfx.dat supplies
surface-fire counts/ranges, and the pinned engine supplies the arithmetic
implemented in Burning.java. No original members or geometry are published.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

from explosion_metadata import (load_explosions, _sections, _mapping, _read_pointer_word,
                                _read_cstring, _u16, _u32, PMAP)
from inspect_native_bridge import DEFAULT_WASM
from readonly_game_outputs import atomic_write_text, validate_outputs

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'gta5data/data'
OUTPUT = ROOT / 'server/src/main/java/offline/multiplayer/FireCatalog.java'
ENGINE_SHA256 = '11ca8d2c04c5e843d18ff4aea4899d72c86973c6b031df334e67c446b2ae83e0'
EXPECTED = {
    'common/data/effects/explosionfx.dat': 'a4fd70098566d48d5eb24586adec9ceec2c945cd29528d80b51c9cd31599a6be',
    'x64/data/metadata/explosion.ymt': '15d3d6d5f0327d6e50db763957827f1095265244eee20c76bf66513520b4c41e',
}


def joaat(text):
    value = 0
    for byte in text.lower().encode('ascii'):
        value = (value + byte) & 0xffffffff
        value = (value + (value << 10)) & 0xffffffff
        value ^= value >> 6
    value = (value + (value << 3)) & 0xffffffff
    value ^= value >> 11
    return (value + (value << 15)) & 0xffffffff


def load(data_root=DATA, wasm=DEFAULT_WASM):
    paths = [data_root / name for name in EXPECTED] + [wasm]
    hashes = {str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in paths}
    if hashes[str(wasm)] != ENGINE_SHA256:
        raise ValueError('Unsupported original fire engine version')
    for name, digest in EXPECTED.items():
        if hashes[str(data_root / name)] != digest:
            raise ValueError('Unsupported original fire metadata: ' + name)
    vfx = {}
    lines = (data_root / 'common/data/effects/explosionfx.dat').read_text().splitlines()
    if lines[0] != '4.00':
        raise ValueError('Unsupported explosionfx.dat version')
    for line in lines:
        parts = line.split()
        if not parts or not parts[0].startswith('EXP_VFXTAG_'):
            continue
        if len(parts) != 21:
            raise ValueError('Invalid explosion VFX row')
        numbers = [struct.unpack('<f', struct.pack('<f', float(value)))[0] for value in parts[9:]]
        if any(not math.isfinite(v) or v < 0 for v in numbers):
            raise ValueError('Invalid fire number')
        if any(numbers[i] > numbers[i + 1] for i in (0, 2, 4, 6, 8)):
            raise ValueError('Invalid fire range')
        if numbers[0] != int(numbers[0]) or numbers[1] != int(numbers[1]) or numbers[1] > 32:
            raise ValueError('Invalid fire count')
        key = joaat(parts[0])
        if key in vfx:
            raise ValueError('Duplicate VFX hash')
        vfx[key] = {'vfx': parts[0], 'numbers': numbers}
    pso = data_root / 'x64/data/metadata/explosion.ymt'
    records = load_explosions(pso)  # validates the supported schema and every record
    data = pso.read_bytes()
    root_id, mapping = _mapping(_sections(data)[PMAP])
    root = data[mapping[root_id - 1]['offset']:]
    block, offset = _read_pointer_word(root[8:16])
    start = mapping[block - 1]['offset'] + offset
    result = []
    for index in range(_u16(root, 16)):
        row = data[start + index * 120:start + (index + 1) * 120]
        name = _read_cstring(data, mapping, row[8:16])
        if name not in records:
            raise ValueError('Explosion identity mismatch')
        key = _u32(row, 96)
        if key in vfx:
            result.append({'explosion': name, 'vfx_hash': key, **vfx[key]})
    for path in paths:
        if hashlib.sha256(path.read_bytes()).hexdigest() != hashes[str(path)]:
            raise ValueError('Original fire input changed during read')
    return result, hashes


def generate(rows):
    entries = []
    for row in rows:
        n = row['numbers']
        values = ', '.join([str(int(n[0])), str(int(n[1]))] + [repr(v) + 'f' for v in n[2:]])
        entries.append(f'        rules.put("{row["explosion"]}", new Rule("{row["vfx"]}", {values}));')
    return '''package offline.multiplayer;

import java.util.LinkedHashMap;
import java.util.Map;

/** Generated by tools/fire_metadata.py from original explosion.ymt + explosionfx.dat. */
final class FireCatalog {
    private FireCatalog() {}
    static final String ENGINE_SHA256 = "''' + ENGINE_SHA256 + '''";
    static final String VFX_SHA256 = "''' + EXPECTED['common/data/effects/explosionfx.dat'] + '''";
    record Rule(String vfx, int countMin, int countMax, float rangeMin, float rangeMax,
            float lifeMin, float lifeMax, float strengthMin, float strengthMax,
            float peakMin, float peakMax, float fuel, float burnRate) {}
    private static final Map<String, Rule> RULES;
    static {
        var rules = new LinkedHashMap<String, Rule>();
''' + '\n'.join(entries) + '''
        RULES = Map.copyOf(rules);
    }
    static Rule byExplosion(String tag) { return RULES.get(tag); }
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-root', type=Path, default=DATA)
    parser.add_argument('--wasm', type=Path, default=DEFAULT_WASM)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--report', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    paths = [args.data_root / name for name in EXPECTED] + [args.wasm]
    outputs = [args.output] + ([args.report] if args.report else [])
    roots = [args.data_root, args.data_root.resolve(), args.wasm.parent]
    for root in tuple(roots):
        if root.name == 'data':
            roots.append(root.parent)
    validate_outputs(outputs, sources=paths, protected_roots=roots)
    rows, hashes = load(args.data_root, args.wasm)
    texts = [generate(rows)]
    if args.report:
        texts.append(json.dumps({'sources': hashes, 'rows': rows}, indent=2, sort_keys=True) + '\n')
    for path, text in zip(outputs, texts):
        if args.check:
            if not path.is_file() or path.read_text() != text:
                parser.exit(1, str(path) + ' differs from the original fire metadata\n')
        else:
            atomic_write_text(path, text, sources=paths, protected_roots=roots)
    print(f'Original fire catalog verified: {len(rows)} explosion mappings')


if __name__ == '__main__':
    main()
